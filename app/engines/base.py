"""Data types and protocols shared by the speech-to-text, text-to-speech, LLM and acceptability engines.

An engine may also expose a `detail` string (device in use, error text, fix hint);
`/api/health` reports it when present.
"""

from __future__ import annotations

import math
import re
from collections.abc import Mapping
from dataclasses import dataclass, field
from typing import Protocol, runtime_checkable

VOICE_LANGS = ("lb", "en")
# rate: speaking-rate multiplier, 1.0 is the voice's own speed and lower is slower.
# pitch: semitones, negative is lower. volume: linear gain.
VOICE_RANGES = {"rate": (0.5, 1.5), "pitch": (-6.0, 6.0), "volume": (0.2, 2.0)}
SENTENCE_END = re.compile(r"""[.!?…]["'“”«»‘’]*\s*\Z""")


SYNTHETIC_COMMENT = "Synthetic speech generated by an AI text-to-speech system; not a recording of a person."
SOFTWARE_TAG = "Luxembourgish voice tutor (Piper TTS)"


def wav_chunks(wav: bytes) -> list[tuple[bytes, int, int]] | None:
    """(id, start of the data, size) of each chunk of a RIFF/WAVE file; None when it is not one."""
    if len(wav) < 12 or wav[:4] != b"RIFF" or wav[8:12] != b"WAVE":
        return None
    chunks = []
    position = 12
    while position < len(wav):
        if position + 8 > len(wav):
            return None
        size = int.from_bytes(wav[position + 4 : position + 8], "little")
        start = position + 8
        if start + size > len(wav):
            return None
        chunks.append((wav[position : position + 4], start, size))
        position = start + size + (size & 1)
    return chunks


def info_chunk(fields: list[tuple[bytes, str]]) -> bytes:
    """A RIFF `LIST` chunk of type `INFO`; each value is NUL-terminated and padded to an even length."""
    body = b"INFO"
    for tag, value in fields:
        data = value.encode("utf-8") + b"\0"
        data += b"\0" * (len(data) & 1)
        body += tag + len(data).to_bytes(4, "little") + data
    return b"LIST" + len(body).to_bytes(4, "little") + body


def mark_synthetic(wav: bytes) -> bytes:
    """`wav` with a RIFF INFO comment saying the speech is synthetic (AI Act Art. 50(2)).

    Bytes that are not a RIFF/WAVE file, and a file that has the comment already, come back unchanged.
    """
    chunks = wav_chunks(wav)
    if not chunks:
        return wav
    for chunk_id, start, size in chunks:
        if chunk_id == b"LIST" and wav[start : start + 4] == b"INFO" and b"ICMT" in wav[start + 4 : start + size]:
            return wav
    end = chunks[-1][1] + chunks[-1][2]
    end += end & 1
    marked = wav[:end].ljust(end, b"\0") + info_chunk([(b"ISFT", SOFTWARE_TAG), (b"ICMT", SYNTHETIC_COMMENT)])
    return marked[:4] + (len(marked) - 8).to_bytes(4, "little") + marked[8:]


def ends_sentence(text: str) -> bool:
    """Whether the text of a segment ends in . ! ? or …; closing quotes may follow it."""
    return bool(SENTENCE_END.search(text))


def voice_tuning(settings, voice: Mapping | None = None) -> dict[str, dict[str, float]]:
    """Rate, pitch and volume per language: the settings with `voice` laid over, clamped.

    `voice` is {"lb": {"rate", "pitch", "volume"}, "en": {...}} with every key optional.
    Unknown languages and keys are ignored; anything that is not a number raises ValueError.
    """
    if voice is None:
        voice = {}
    if not isinstance(voice, Mapping):
        raise ValueError("voice is not an object")
    tuning = {}
    for lang in VOICE_LANGS:
        given = voice.get(lang, {})
        if not isinstance(given, Mapping):
            raise ValueError(f"voice.{lang} is not an object")
        tuning[lang] = {}
        for key, (low, high) in VOICE_RANGES.items():
            value = given.get(key, getattr(settings, f"tts_{key}_{lang}"))
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"voice.{lang}.{key} is not a number: {value!r}")
            tuning[lang][key] = min(max(float(value), low), high)
    return tuning


@dataclass
class Segment:
    lang: str  # "lb" or "en"
    text: str


@dataclass
class Transcript:
    text: str
    language: str
    duration_s: float
    segments: list[dict] = field(default_factory=list)


@dataclass
class WavAudio:
    wav_bytes: bytes
    sample_rate: int
    # One {"index", "lang", "start_s", "end_s"} per synthesized segment, in seconds.
    segment_offsets: list[dict] = field(default_factory=list)


@dataclass
class Turn:
    role: str  # "user" or "tutor"
    text: str
    segments: list[Segment] = field(default_factory=list)
    mode: str = "chat"


@dataclass
class TutorReply:
    segments: list[Segment]
    new_phrases: list[dict] = field(default_factory=list)  # {"lb", "en"}
    mode: str = "chat"  # or "teacher"
    claims: list[dict] = field(default_factory=list)  # {"form", "lemma"}


VERDICTS = ("good", "fix", "english", "unclear")


@dataclass
class Judgement:
    """What the tutor makes of one practice answer, as the model gave it."""

    verdict: str  # one of VERDICTS
    reaction_en: str  # what the tutor says first, whatever the verdict
    quote: str = ""  # "fix": the learner's words the correction is about
    better_lb: str = ""  # "fix" and "english": the Luxembourgish to say instead
    why_en: str = ""  # "fix": what leads from the quote to the better version
    claims: list[dict] = field(default_factory=list)  # {"form", "lemma"} of the words of better_lb


@dataclass
class WrapUpText:
    """What the tutor says looking back on a practice talk, as the model gave it: one short text per heading."""

    words_en: str
    grammar_en: str
    task_en: str  # how the learner got across what they meant


# A look back that is true of any talk: the fake engine's own and the provider engine's fallback.
TEMPLATE_WRAP_UP = WrapUpText(
    "You found a word for everything we talked about.",
    "Your sentences held together.",
    "I could follow you the whole way.",
)


class LLMError(Exception):
    """An LLM failure; `kind` is "auth", "timeout", "schema" or "other"."""

    def __init__(self, kind: str, detail: str = "") -> None:
        super().__init__(f"{kind}: {detail}" if detail else kind)
        self.kind = kind
        self.detail = detail


@runtime_checkable
class STTEngine(Protocol):
    name: str

    def ready(self) -> bool: ...

    def warmup(self) -> None: ...

    def transcribe(self, audio_bytes: bytes, mime: str) -> Transcript: ...


@runtime_checkable
class TTSEngine(Protocol):
    name: str

    def ready(self) -> bool: ...

    def warmup(self) -> None: ...

    def synthesize(
        self, segments: list[Segment], voice: Mapping | None = None, respell: Mapping | None = None
    ) -> WavAudio: ...


@runtime_checkable
class LLMEngine(Protocol):
    name: str

    def ready(self) -> bool: ...

    def warmup(self) -> None: ...

    def reply(self, history: list[Turn], mode: str, grounding: str) -> TutorReply: ...

    def judge(
        self, question_lb: str, question_en: str, answer: str, grounding: str, extra: str = ""
    ) -> Judgement: ...

    def wrap_up(self, facts: str) -> WrapUpText: ...


